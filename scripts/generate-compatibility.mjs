import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, resolve, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { validateMatrix } from '../src/core/compatibility/evaluate.mjs';
import { messages } from '../src/core/i18n/catalogs/compatibility.mjs';
const root = fileURLToPath(new URL('..', import.meta.url));
const sourceDir = join(root, 'src/core/compatibility');
const notice = 'Generated by scripts/generate-compatibility.mjs. Edit src/core/compatibility/ or the compatibility catalog; do not edit this file.';
const json = value => JSON.stringify(value, null, 2) + '\n';

export function matrixTable(matrix, locale) {
  const t = messages[locale], chinese = locale === 'zh-CN';
  const lines = [`# ${t.matrix}`, '', `Product ${matrix.productVersion} · matrix ${matrix.revision} · reviewed ${matrix.reviewedOn}`, '',
    chinese ? '能力检测与产品认证分别报告。未验证不表示已知不能运行；测试浏览器不能代替真实设备认证。' : 'Capabilities and product certification are separate. Unverified does not mean known to fail. Test browsers do not certify physical devices.', '',
    `| ${t.target} | ${t.versions} | ${t.certification} | ${t.scope} | ${t.evidence} |`, '| --- | --- | --- | --- | --- |'];
  for (const target of matrix.targets) lines.push(`| ${target.id} (${[target.os, target.osRelease, target.arch].filter(Boolean).join(' ') || '—'}) | ${target.minMajor === null ? '—' : `${target.minMajor}–${target.maxMajor}`} | ${t[target.level]} | ${target.workflows.map(value => t[value]).join(' / ')} | ${target.evidence.join(', ') || t.none} |`);
  lines.push('', `| ${t.hardware} | ${t.certification} | ${t.minimum} |`, '| --- | --- | --- |');
  for (const profile of matrix.hardwareProfiles) lines.push(`| ${t[profile.id] ?? profile.id} | ${t[profile.status]} | ${profile.minimum === null ? t.notEstablished : JSON.stringify(profile.minimum)} |`);
  lines.push('', t.limits, '', t.certificate, '',
    chinese ? '滚动认证目标：发布时当前稳定版及前一主版本；只有上表列出的有限范围已认证。企业冻结版本须单独记录。' : 'Rolling certification targets the stable major at release and its predecessor. Only finite certified ranges in the table are commitments. Enterprise frozen versions require a separate record.', '',
    chinese ? '完整 Appliance 还要求 OPFS 往返、健康与 WSS 验收；单文件演示按 L2-2 的独立能力范围验收。客户端无需浏览器扩展，部署服务与 XR 系统组件另列。' : 'The full Appliance additionally requires OPFS, service health and WSS acceptance. Single-file demos follow the separate L2-2 scope. Browser extensions are not required; deployment services and XR system components are separate.', '');
  for (const evidence of matrix.evidence) lines.push(`- ${evidence.id}: ${evidence.kind}, ${evidence.os} / ${evidence.browser} ${evidence.major}, ${evidence.runDate}, build ${evidence.build}; ${evidence.report}`, '');
  return lines.join('\n');
}

/** v1 cannot express OS/scenario-limited certificates, so never broadens them. */
export function legacyProjection(matrix) {
  return { $comment: notice, schemaVersion: 1, lastReviewed: matrix.reviewedOn,
    browsers: Object.fromEntries(['chromium', 'edge', 'firefox', 'safari'].map(browser => [browser, { minimumMajor: null, testedMajor: null, level: 'diagnostic-only' }])),
    features: { secureContext: 'required', webgl2: 'required', opfsRoundTrip: 'required', fileSystemAccess: 'authoring', webgpu: 'feature', webxr: 'feature' } };
}

export function generatedCompatibilityFiles() {
  const matrix = JSON.parse(readFileSync(join(sourceDir, 'support-matrix.json'), 'utf8'));
  const errors = validateMatrix(matrix);
  if (errors.length) throw new Error(errors.join(', '));
  if (matrix.productVersion !== JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).version) throw new Error('MATRIX_PRODUCT_VERSION_DRIFT');
  for (const evidence of matrix.evidence) {
    const report = JSON.parse(readFileSync(join(root, evidence.report), 'utf8'));
    for (const key of ['productVersion', 'build', 'os', 'osRelease', 'arch', 'browser', 'major', 'gpu', 'status']) {
      if (report[key] !== evidence[key]) throw new Error(`MATRIX_EVIDENCE_DRIFT:${evidence.id}:${key}`);
    }
    if (!evidence.workflows.every(workflow => report.workflows?.includes(workflow))) throw new Error(`MATRIX_EVIDENCE_SCOPE:${evidence.id}`);
    if (evidence.kind === 'hardware' && report.physicalDeviceVerified !== true) throw new Error(`MATRIX_HARDWARE_UNVERIFIED:${evidence.id}`);
  }
  const files = new Map();
  for (const base of ['public/compatibility', 'appliance/runtime/static/diagnostics/compatibility']) {
    for (const name of ['evaluate.mjs', 'probes.mjs', 'page.mjs', 'page.css']) files.set(`${base}/${name}`, `${name.endsWith('.css') ? `/* ${notice} */` : `// ${notice}`}\n${readFileSync(join(sourceDir, name), 'utf8')}`);
    files.set(`${base}/index.html`, `<!-- ${notice} -->\n${readFileSync(join(sourceDir, 'page.html'), 'utf8')}`);
    files.set(`${base}/messages.mjs`, `// ${notice}\n${readFileSync(join(root, 'src/core/i18n/catalogs/compatibility.mjs'), 'utf8')}`);
    files.set(`${base}/support-matrix.json`, json({ $comment: notice, ...matrix }));
    files.set(`${base}/matrix.mjs`, `// ${notice}\nexport default ${json(matrix).trim()};\n`);
    for (const locale of ['zh-CN', 'en-US']) files.set(`${base}/SUPPORT_MATRIX.${locale}.md`, `<!-- ${notice} -->\n\n${matrixTable(matrix, locale)}`);
  }
  // Type declarations are only needed for source consumers, not for served pages.
  files.set('appliance/runtime/static/diagnostics/compatibility/evaluate.d.mts', `// ${notice}\n${readFileSync(join(sourceDir, 'evaluate.d.mts'), 'utf8')}`);
  files.set('appliance/runtime/static/diagnostics/support-matrix.json', json(legacyProjection(matrix)));
  for (const locale of ['zh-CN', 'en-US']) {
    const body = matrixTable(matrix, locale);
    files.set(`appliance/docs/SUPPORT_MATRIX.${locale}.md`, `<!-- ${notice} -->\n\n${body}`);
    files.set(`docs/generated/COMPATIBILITY_MATRIX.${locale}.md`, `---\ndoc_id: GENERATED-COMPAT-${locale.toUpperCase()}\ntitle: ${locale === 'zh-CN' ? '发布兼容性矩阵' : 'Release compatibility matrix'}\nstatus: generated\nowner: engineering\nlast_reviewed: ${matrix.reviewedOn}\nauthority: generated\n---\n\n<!-- ${notice} -->\n\n${body}`);
  }
  return files;
}

export function generateCompatibility(checkOnly = false) {
  const drift = [];
  for (const [path, content] of generatedCompatibilityFiles()) {
    const absolute = join(root, path);
    if (checkOnly) {
      if (!existsSync(absolute) || readFileSync(absolute, 'utf8') !== content) drift.push(path);
    } else { mkdirSync(dirname(absolute), { recursive: true }); writeFileSync(absolute, content); }
  }
  if (drift.length) throw new Error(`Compatibility generated files drifted:\n${drift.join('\n')}`);
}
if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  generateCompatibility(process.argv.includes('--check'));
  console.log('[compatibility] generated resources and evidence are consistent');
}
